import { calculatePhysicalReturnBreakdown, calculateReturnBreakdown, parseReturnQuantityInput, validateReturnQuantity } from '../returnReconciliation.ts'

const assert = (condition: unknown, message: string) => {
  if (!condition) throw new Error(`FAIL: ${message}`)
  console.log(`PASS: ${message}`)
}

const a = calculateReturnBreakdown(6, 6, 0.46)
assert(a.apt === 5.54 && a.waste === 0.46 && a.shortage === 0 && a.overage === 0, '6 kg recibidos con 0,46 kg de merma dejan 5,54 kg aptos sin diferencia')
const b = calculateReturnBreakdown(9, 9, 0.44)
assert(b.apt === 8.56 && b.waste === 0.44 && b.shortage === 0 && b.overage === 0, '9 kg recibidos con 0,44 kg de merma dejan 8,56 kg aptos sin diferencia')
const c = calculateReturnBreakdown(6, 5.8, 0.46)
assert(c.apt === 5.34 && c.shortage === 0.2 && c.overage === 0, 'faltante se calcula desde la recepción física, no desde el retorno apto')
const d = calculateReturnBreakdown(6, 6.46, 0)
assert(d.apt === 6 && d.overage === 0.46 && d.shortage === 0, 'el sobrante físico sobre lo esperado va a cuarentena')
const e = calculateReturnBreakdown(6, 6.46, 0.46)
assert(e.apt === 5.54 && e.waste === 0.46 && e.overage === 0.46 && e.shortage === 0, 'merma y sobrante se separan aunque ocurran juntos')
const invalidWaste = calculateReturnBreakdown(6, 0.4, 0.46)
assert(!invalidWaste.wasteValid, 'merma mayor a la recepción física queda inválida para bloquear el guardado')
assert(!validateReturnQuantity('package', 1.5), 'paquetes rechazan fracciones')
assert(validateReturnQuantity('kg', 1.5), 'kilogramos admiten decimales')
assert(!validateReturnQuantity('kg', -1), 'ninguna unidad permite retorno negativo')
const exact2 = calculatePhysicalReturnBreakdown(2, 1.84, 0.16, 0)
assert(exact2.totalReceived === 2 && exact2.sellableFromDispatch === 2 && exact2.shortage === 0 && exact2.overage === 0, '1,84 normal + 0,16 de merma vuelve exactamente 2 kg al stock')
const exact6 = calculatePhysicalReturnBreakdown(6, 5.54, 0.46, 0)
assert(exact6.sellableFromDispatch === 6 && exact6.shortage === 0, '5,54 normal + 0,46 de merma recuperable devuelve 6 kg')
const exact9 = calculatePhysicalReturnBreakdown(9, 8.56, 0.44, 0)
assert(exact9.sellableFromDispatch === 9 && exact9.shortage === 0, '8,56 normal + 0,44 de merma recuperable devuelve 9 kg')
const short = calculatePhysicalReturnBreakdown(2, 1.8, 0.1, 0)
assert(short.totalReceived === 1.9 && short.shortage === 0.1, 'retorno total de 1,9 kg deja faltante de 0,1 kg')
const withNonSellable = calculatePhysicalReturnBreakdown(2, 1.84, 0.16, 0.1)
assert(withNonSellable.totalReceived === 2.1 && withNonSellable.sellableReturn === 2 && withNonSellable.overage === 0.1 && withNonSellable.sellableOverage === 0, 'producto no apto se suma una vez al total físico, pero nunca al stock vendible')
const exactPhysicalMix = calculatePhysicalReturnBreakdown(2, 1.7, 0.2, 0.1)
assert(exactPhysicalMix.totalReceived === 2 && exactPhysicalMix.sellableFromDispatch === 1.9 && exactPhysicalMix.nonSellableReturn === 0.1 && exactPhysicalMix.shortage === 0, '1,7 normal + 0,2 de merma recuperable + 0,1 no apto recibe 2 kg y devuelve 1,9 kg vendibles')
const shortWithMerma = calculatePhysicalReturnBreakdown(2, 1.7, 0.2, 0)
assert(shortWithMerma.totalReceived === 1.9 && shortWithMerma.shortage === 0.1, '1,7 normal + 0,2 de merma deja faltante de 0,1 kg')
const quarantinedExcess = calculatePhysicalReturnBreakdown(2, 2.1, 0, 0)
assert(quarantinedExcess.sellableReturn === 2.1 && quarantinedExcess.sellableFromDispatch === 2 && quarantinedExcess.sellableOverage === 0.1 && quarantinedExcess.overage === 0.1, 'sobrante vendible sobre el despacho queda separado para cuarentena')
assert(parseReturnQuantityInput('1.84') === 1.84, 'campo acepta decimal con punto')
assert(parseReturnQuantityInput('1,84') === 1.84, 'campo normaliza decimal con coma')
assert(parseReturnQuantityInput('1,') === null, 'decimal incompleto se conserva para seguir escribiendo y se valida al confirmar')
console.log('Suite de rendición de retorno: 20 comprobaciones.')
